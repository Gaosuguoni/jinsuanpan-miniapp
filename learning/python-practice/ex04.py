# 练习4：把 "50斤" 拆成数量 50 和单位 "斤"
#
# 提示：
#   s[-1]   取最后一个字符            → "斤"
#   s[:-1]  取除最后一个以外的部分     → "50"（还是字符串！）
#   int("50") 把字符串转成数字         → 50
#
# 目标输出：
#   数量: 50 单位: 斤
#
# 进阶（选做）：如果单位是两个字的"50公斤"怎么办？
#   提示：用循环找到"第一个不是数字的字符"的位置

def split_qty(s):
    unit = s[-1]
    qty_str = s[:-1]
    qty = int(qty_str)
    return qty,unit


print(split_qty("50斤"))

